function render(name) {
  const out = join(root, 'out', name);
  mkdirSync(out, { recursive: true });
  const start = performance.now();
  const run = spawnSync(process.execPath, [join(root, 'main.ts')], {
    cwd: root, env: { ...process.env, MAKEFUN_OUTPUT_DIR: out, MAKEFUN_QA: '1' },
    encoding: 'utf8', timeout: 60000,
  });
  assert.equal(run.status, 0, run.stderr || run.error?.message);
  const elapsed = performance.now() - start;
  assert(elapsed < 60000);
  console.log(`PASS ${name}: ${elapsed.toFixed(0)} ms; ${run.stdout.trim()}`);
  return { out, bytes: readFileSync(join(out, 'entry.png')) };
}
function crc32(bytes) {
  let crc = 0xffffffff;
  for (const byte of bytes) {
    crc ^= byte;
    for (let i = 0; i < 8; i++) crc = (crc >>> 1) ^ ((crc & 1) ? 0xedb88320 : 0);
  }
  return (crc ^ 0xffffffff) >>> 0;
}
function decode(bytes, expectedSize) {
  assert.deepEqual([...bytes.subarray(0, 8)], [137, 80, 78, 71, 13, 10, 26, 10]);
  const compressed = [], types = [];
  let offset = 8, width, height;
  while (offset < bytes.length) {
    const length = bytes.readUInt32BE(offset), type = bytes.toString('ascii', offset + 4, offset + 8);
    assert(offset + length + 12 <= bytes.length, 'Truncated chunk');
    const data = bytes.subarray(offset + 8, offset + 8 + length);
    assert.equal(crc32(bytes.subarray(offset + 4, offset + 8 + length)), bytes.readUInt32BE(offset + 8 + length), `CRC: ${type}`);
    types.push(type);
    if (type === 'IHDR') {
      width = data.readUInt32BE(0); height = data.readUInt32BE(4);
      assert.equal(data[8], 8); assert.equal(data[9], 2);
      assert.equal(data[10], 0); assert.equal(data[11], 0); assert.equal(data[12], 0);
    }
    if (type === 'IDAT') compressed.push(data);
    offset += length + 12;
    if (type === 'IEND') { assert.equal(length, 0); break; }
  }
  assert.equal(offset, bytes.length, 'Trailing bytes');
  assert.deepEqual(types, ['IHDR', 'IDAT', 'IEND']);
  assert.equal(width, expectedSize); assert.equal(height, expectedSize);
  const raw = inflateSync(Buffer.concat(compressed)), stride = width * 3 + 1;
  assert.equal(raw.length, stride * height);
  let changed = 0;
  for (let y = 0; y < height; y++) {
    assert.equal(raw[y * stride], 0);
    for (let x = 0; x < width; x++) {
      const p = y * stride + 1 + 3 * x;
      if (raw[p] !== 13 || raw[p + 1] !== 17 || raw[p + 2] !== 21) changed++;
    }
  }
  assert(changed > width * height * 0.10 && changed < width * height * 0.45, 'Blank or overcrowded image');
  return { raw, stride, width, changed };
}
