function scan(dir) {
  for (const item of readdirSync(dir, { withFileTypes: true })) {
    if (item.name === '.git') continue;
    const path = join(dir, item.name);
    if (item.isDirectory()) { scan(path); continue; }
    if (!item.isFile()) continue;
    let data = readFileSync(path).toString('utf8');
    if (path === join(root, 'README.md')) data = data.replace(/<!--[\s\S]*?-->/g, '');
    for (const scheme of ['ht' + 'tp://', 'ht' + 'tps://']) assert(!data.includes(scheme), `Network URL in ${item.name}`);
    assert(!data.includes('/home/' + 'ubuntu/'), 'Personal home path in repository');
  }
}
